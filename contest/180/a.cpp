using ll = long long;

void solve() {
    int b, r;
    cin >> b >> r;
    int total = 30 * 30;
    int first = 30 * b;
    int second = 30 * r;
    int third = b * r;
    cout << total - first - second + third << endl;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    while (t--) solve();
}
